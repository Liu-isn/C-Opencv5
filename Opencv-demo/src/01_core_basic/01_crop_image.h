//
// 学习目标：
//   1. 掌握使用 Range() 和 Rect() 进行 ROI 裁剪
//   2. 理解 ROI 是视图(view)还是深拷贝(clone)
//   3. 学会裁剪前的边界校验
//   4. 学会把大图分成小块(patch)
//   5. 理解坐标转换在 resize/crop 中的重要性
//
// 核心概念：
//   OpenCV 没有专门的 crop 函数
//   裁剪操作通过 ROI (Region of Interest) 实现：
//     C++: img(Range(y1,y2), Range(x1,x2))
//     或    img(Rect(x, y, w, h))
//
// 关键区别：
//   img(Rect)  返回的是"视图"(view)，共享原图像素数据
//   .clone()   返回的是"深拷贝"(copy)，独立存储
//   .copyTo()  也是深拷贝，需要目标 Mat
//
// 什么时候需要 clone？
//   1. 裁剪后的小图要长期保留，而原图可能被释放
//   2. 需要修改裁剪区域，但不能影响原图
//   3. 批量处理时，避免小视图 keeping 大 buffer
//
// 与 CT 的联系：
//   CT 图像裁剪常用于：
//     - 去除扫描床等无关区域
//     - 提取特定解剖部位（如肺部、肝脏）
//     - 3D 体数据的 sub-volume 提取
//     - 切片级别的局部分析
// ============================================================

